"""3.32: the written financial report, periodic reports, and the extra dashboard filters."""
from playwright.sync_api import sync_playwright
from ui_lib import *
t = demo_token('r332ui')
with sync_playwright() as pw:
    b = pw.chromium.launch()
    pg, errs = signed_in(b, t)
    # ── written report ──
    pg.goto(B + '/financial-report'); pg.wait_for_selector('[data-fin-report]', timeout=60000)
    ok('التقرير المالي المكتوب' in pg.inner_text('.sidebar') and 'التقارير المالية الدورية' in pg.inner_text('.sidebar'), 'both screens are in the reports menu')
    secs = pg.locator('[data-fin-report] [data-section]').count()
    ok(secs >= 8, f'report sections rendered ({secs})')
    ok(pg.locator('[data-verdict]').count() == 1 and pg.locator('[data-check]').count() >= 6, 'verdict, books checks and obligations shown')
    body = pg.inner_text('[data-fin-report]')
    EG = PORT == '3200'
    ok('الملخص التنفيذي' in body and (('الالتزامات النظامية (مصر)' in body and 'إقرار ضريبة القيمة المضافة (14%)' in body and 'ضريبة كسب العمل' in body) if EG else ('الالتزامات النظامية (السعودية)' in body and 'إقرار ضريبة القيمة المضافة (15%)' in body and 'مكافأة نهاية الخدمة' in body)), 'obligations of the edition (Egypt / Saudi)')
    before = pg.inner_text('[data-fin-report] .fr-head')
    pg.click('button:has-text("الشهر الماضي")'); pg.wait_for_timeout(2500)
    ok(pg.inner_text('[data-fin-report] .fr-head') != before, 'period preset re-issues the report for last month')
    ok(pg.locator('button:has-text("طباعة")').count() >= 1, 'print / PDF available')
    # ── dashboard filters ──
    pg.goto(B + '/insights'); pg.wait_for_selector('.kpis', timeout=60000)
    cmp0 = pg.inner_text('.insights .card >> nth=0')
    pg.select_option('[data-compare]', 'yoy'); pg.wait_for_timeout(2500)
    ok(pg.inner_text('.insights .card >> nth=0') != cmp0, 'comparison switched to the same period last year')
    pg.click('[data-more-filters]'); pg.wait_for_selector('[data-filters]')
    k0 = pg.inner_text('.kpis')
    pg.get_by_label('قناة البيع').select_option('POS'); pg.wait_for_timeout(2500)
    ok(pg.inner_text('.kpis') != k0 and pg.locator('[data-doc-only]').count() == 1, 'channel filter recalculates and explains the ledger figures')
    ok('غير قابلة للتقسيم بالفلتر' in pg.inner_text('.kpis'), 'operating expenses shown as not divisible by channel')
    pg.click('button:has-text("مسح الفلاتر")'); pg.wait_for_timeout(2000)
    ok('من الدفاتر' in pg.inner_text('.kpis'), 'without filters the operating result comes from the ledger')
    pg.click('a:has-text("التقرير المكتوب")'); pg.wait_for_selector('[data-fin-report]', timeout=60000)
    ok('/financial-report' in pg.url and 'from=' in pg.url, 'the dashboard opens the written report for the same period')
    # ── periodic reports ──
    pg.goto(B + '/periodic-reports'); pg.wait_for_selector('[data-periodic-list]', timeout=60000)
    ok(pg.locator('[data-periodic-list] tbody tr').count() == 1 and 'تلقائياً' in pg.inner_text('[data-periodic-list]'), "last month's report issued on first visit")
    ok(pg.locator('[data-auto-settings] input').count() == 3, 'automatic issue switches for monthly, quarterly, annual')
    pg.get_by_label('نوع التقرير').select_option('QUARTER')
    pg.click('[data-issue]'); pg.wait_for_selector('[data-fin-report]', timeout=60000)
    ok('/periodic-reports/' in pg.url and 'ربع سنوي' in pg.inner_text('[data-fin-report] h2'), 'issuing opens the quarterly report')
    ok(pg.locator('[data-reissue]').count() == 1, 're-issue button')
    pg.click('a:has-text("التقارير الدورية")'); pg.wait_for_selector('[data-periodic-list]')
    ok(pg.locator('[data-periodic-list] tbody tr').count() == 2, 'both reports listed')
    ok(not errs, 'no page errors ' + str(errs[:2]))
    # ── phone width ──
    pm, e3 = signed_in(b, t, viewport={'width': 390, 'height': 844})
    pm.goto(B + '/financial-report'); pm.wait_for_selector('[data-fin-report]', timeout=60000)
    ok(pm.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 2'), 'phone: no sideways scroll')
    # ── English ──
    pe, e2 = signed_in(b, t, 'en')
    pe.goto(B + '/financial-report'); pe.wait_for_selector('[data-fin-report]', timeout=60000)
    heads = ' '.join(pe.locator('[data-fin-report] h3 span').all_inner_texts())
    ok(not AR.search(heads) and 'Executive summary' in heads, 'English: section headings in English ' + heads[:80])
    ok(not AR.search(pe.inner_text('[data-fin-report] [data-section="summary"]')), 'English: the summary text is English')
    pe.goto(B + '/periodic-reports'); pe.wait_for_selector('[data-periodic-list]')
    ok(not AR.search(pe.inner_text('[data-periodic] .card-h')), 'English: periodic reports screen translated')
    ok(not e2 and not e3, 'English / phone: no page errors ' + str((e2 + e3)[:2]))
    b.close()
done()
